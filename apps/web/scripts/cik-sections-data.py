#!/usr/bin/env python3
"""Pack the CIK section addresses and voter counts into src/signup/cik-sections.data.ts.

Sources (download from cik.bg, then run from apps/web):
  - Adresi-Izb-Sekcii.xlsx: CIK addresses of the polling sections for 25.10.2026
    (Област код, Област текст, Община код, Община, Район код, Район, Секция, Населено място код, Населено място, Адрес)
  - obsht_broi_sekcii_izbirateli_predvaritelni_ПВП-04-09-2026.xlsx: voters per section, preliminary lists
  - r336-Pril-SIK izvan stranata-glasuvane sas SUMG-АД.xlsx: abroad sections that vote by machine (решение 336)
  python3 scripts/cik-sections-data.py <adresi.xlsx> <broi.xlsx> <r336.xlsx> > src/signup/cik-sections.data.ts
Needs openpyxl. No personal data: only section codes, places and counts.
"""
import json
import re
import sys

import openpyxl


def rows(path, skip):
    return list(openpyxl.load_workbook(path, read_only=True).active.iter_rows(values_only=True))[skip:]


def text(value):
    return ' '.join(str(value or '').split())


# The CIK files number by област; section codes start with the МИР. Пловдив (област 16) is МИР 16
# for the city (община 22) and МИР 17 for the rest; София-град (област 22) is МИР 23, 24 or 25 by
# район; every later област shifts by those three extra МИР.
SOFIA_DISTRICT_MIR = {
    '01': '24', '02': '23', '03': '24', '04': '24', '05': '24', '06': '24', '07': '24', '08': '23',
    '09': '23', '10': '23', '11': '25', '12': '25', '13': '25', '14': '24', '15': '23', '16': '23',
    '17': '23', '18': '25', '19': '25', '20': '25', '21': '25', '22': '24', '23': '23', '24': '25',
}


def mir_of(oblast, municipality, district):
    o = int(oblast)
    if o <= 15:
        return f'{o:02d}'
    if o == 16:
        return '16' if municipality == '22' else '17'
    if o <= 21:
        return f'{o + 1:02d}'
    if o == 22:
        return SOFIA_DISTRICT_MIR[district]
    return f'{o + 3:02d}'


def code(oblast, municipality, district, section):
    oblast = f'{text(oblast):0>2}'
    municipality = f'{text(municipality):0>2}'
    district = f'{text(district) or "00":0>2}'
    return f'{mir_of(oblast, municipality, district)}{municipality}{district}{text(section):0>3}'


adresi, broi, r336 = sys.argv[1:4]
places = {}
municipalities = {}
for r in rows(adresi, 1):
    if not r[0]:
        continue
    c = code(r[0], r[2], r[4], r[6])
    municipalities[c[:4]] = f'{text(r[1])}|{text(r[3])}'
    places[c] = [text(r[8]), text(r[9])]
voters = {}
for r in rows(broi, 2):
    if r[1] and r[7] and isinstance(r[8], int):
        voters[code(r[1], r[3], r[5], r[7])] = r[8]
machines = sorted({text(r[2]) for r in rows(r336, 1) if re.fullmatch(r'32\d{7}', text(r[2]))})
for c in voters:
    if c not in places:
        places[c] = ['', '']
lines = []
for c in sorted(places):
    town, address = places[c]
    lines.append('\t'.join([c, town.replace('\t', ' '), address.replace('\t', ' '), str(voters.get(c, ''))]))
out = [
    '// Generated by scripts/cik-sections-data.py from the CIK files for 25.10.2026. Do not edit by hand.',
    f'// {len(lines)} domestic sections: code, town, address, voters (preliminary lists; empty when CIK has no count).',
    '// Municipalities: 4-digit prefix → „ОБЛАСТ|ОБЩИНА“. Abroad machine sections: CIK решение 336 (СУМГ).',
    "export const CIK_SECTIONS_AS_OF = '2026-10-25'",
    f'export const CIK_MUNICIPALITIES: Record<string, string> = {json.dumps(dict(sorted(municipalities.items())), ensure_ascii=False)}',
    f'export const CIK_ABROAD_MACHINE_SECTIONS = {json.dumps(" ".join(machines))}',
    f'export const CIK_SECTIONS = {json.dumps(chr(10).join(lines), ensure_ascii=False)}',
    '',
]
sys.stdout.write('\n'.join(out))
