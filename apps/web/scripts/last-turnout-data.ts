// Turn CIK open data (protocols_<date>.txt from export.zip) into src/signup/last-turnout.data.ts.
// Source: https://results.cik.bg/pe202604/opendata/index.html → „изтегли резултати в машинночетим вид“ (export.zip).
// The page sits behind a Cloudflare check, so download export.zip in a browser, unzip it, then:
//   node --experimental-strip-types scripts/last-turnout-data.ts <dir>/protocols_19.04.2026.txt > src/signup/last-turnout.data.ts
// Per protocol line (fields separated by ;): 1 form, 2 section code, 8 „Б. избиратели в списъка“, 10 „2. гласували“.
// Forms 24 (Х) and 26 (ХМ) are domestic; 28/30 are abroad and skipped.
import { readFileSync } from 'node:fs'

const file = process.argv[2]
if (!file) throw new Error('usage: last-turnout-data.ts <protocols.txt>')
const rows: string[] = []
for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
  const fields = line.split(';')
  if (fields[0] !== '24' && fields[0] !== '26') continue
  const code = fields[1]
  const registered = Number(fields[7] || 0)
  const voted = Number(fields[9] || 0)
  if (!/^\d{9}$/.test(code) || !Number.isFinite(registered) || !Number.isFinite(voted)) continue
  rows.push(`${code},${voted},${registered}`)
}
rows.sort()
process.stdout.write(
  [
    `// Generated by scripts/last-turnout-data.ts from CIK open data, ${file.split('/').pop()} (${rows.length} domestic sections).`,
    '// Last election: Избори за народни представители 19.04.2026. Each entry: section code, гласували, избиратели в списъка.',
    `export const LAST_TURNOUT_SOURCE = 'pe202604'`,
    `export const LAST_TURNOUT = '${rows.join(';')}'`,
    '',
  ].join('\n'),
)
