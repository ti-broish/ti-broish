"""Turn the MFA table of abroad sections (numbers and addresses) into src/signup/abroad-section-addresses.data.ts.

Usage: uv run scripts/mfa-abroad-addresses.py <table.xlsx> <as-of YYYY-MM-DD> <source url>
"""
import json
import re
import sys
from pathlib import Path

import openpyxl


def clean(value) -> str:
    return re.sub(r"\s+", " ", str(value or "")).strip()


def main() -> None:
    path, as_of, url = sys.argv[1], sys.argv[2], sys.argv[3]
    sheet = openpyxl.load_workbook(path, read_only=True, data_only=True).worksheets[0]
    sections: dict[str, dict[str, str]] = {}
    country = ""
    for row in sheet.iter_rows(values_only=True):
        cells = [clean(cell) for cell in row[:7]]
        while len(cells) < 7:
            cells.append("")
        _, country_cell, code, place, address, address_local, _ = cells
        # The country is only on the first row of its group; the next row holds „N секции“.
        if country_cell and not re.search(r"\d+\s+секци", country_cell):
            country = country_cell
        code = re.sub(r"\D", "", code)
        if not re.fullmatch(r"32\d{7}", code):
            continue
        entry = {"country": country, "place": place, "address": address or address_local}
        if code in sections and sections[code] != entry:
            raise SystemExit(f"conflicting rows for {code}")
        sections[code] = entry
    out = Path(__file__).resolve().parent.parent / "src/signup/abroad-section-addresses.data.ts"
    lines = [
        "// Generated by scripts/mfa-abroad-addresses.py from the MFA table of abroad sections. Do not edit by hand.",
        "import type { MfaAbroadSection } from './abroad-section-addresses'",
        "",
        f"export const MFA_ABROAD_AS_OF = {json.dumps(as_of)}",
        f"export const MFA_ABROAD_SOURCE = {json.dumps(url)}",
        "",
        "export const MFA_ABROAD_SECTIONS: Record<string, MfaAbroadSection> = {",
    ]
    for code, entry in sorted(sections.items()):
        lines.append(f"  '{code}': {json.dumps(entry, ensure_ascii=False)},")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(sections)} sections, {sum(1 for s in sections.values() if s['address'])} with an address -> {out}")


if __name__ == "__main__":
    main()
