// Turn a priority-sections CSV into the seed SQL for D1 (replaces every row).
//   node --experimental-strip-types scripts/priority-sections-sql.ts src/signup/fixtures/priority-sections-2026-10-19.csv > sql/2026-10-19-priority-sections.sql
import { readFileSync } from 'node:fs'
import { parsePriorityCsv } from '../src/signup/priority-sections.ts'
import { PRIORITY_SECTIONS_INDEXES, PRIORITY_SECTIONS_TABLE } from '../src/signup/priority-sections-sql.ts'

const file = process.argv[2]
if (!file) throw new Error('usage: priority-sections-sql.ts <csv>')
const parsed = parsePriorityCsv(readFileSync(file, 'utf8'))
if (parsed.errors.length) throw new Error(parsed.errors.join('\n'))
const now = process.argv[3] ?? new Date().toISOString()
const q = (value: string) => `'${value.replace(/'/g, "''")}'`
const lines = [
  `-- Domestic priority sections (${parsed.rows.length} rows) from ${file.split('/').pop()}.`,
  '-- Generated by scripts/priority-sections-sql.ts. Admin re-upload on /admin/sections replaces the same table.',
  '-- Apply once per database; deploys do not run it:',
  '--   pnpm exec wrangler d1 execute ti-broish-signup-staging --remote --file sql/2026-10-19-priority-sections.sql',
  '--   pnpm exec wrangler d1 execute ti-broish-signup --remote --file sql/2026-10-19-priority-sections.sql',
  '-- The table only holds this list, so it is rebuilt from scratch.',
  'DROP TABLE IF EXISTS priority_sections;',
  `${PRIORITY_SECTIONS_TABLE.trim()};`,
  ...PRIORITY_SECTIONS_INDEXES.map((sql) => `${sql};`),
  ...parsed.rows.map((row) =>
    `INSERT INTO priority_sections (section_code, town, municipality, oblast, r, level, components, updated_at) VALUES (${[
      q(row.sectionCode), q(row.town), q(row.municipality), q(row.oblast), row.r === null ? 'NULL' : String(row.r), q(row.level), q(JSON.stringify(row.components)), q(now),
    ].join(', ')});`,
  ),
]
process.stdout.write(`${lines.join('\n')}\n`)
